/**
 * The deterministic `crypto` shim: ADK's `randomUUID()` (interrupt ids,
 * client function-call ids, session ids) is served from a named workflow random
 * stream — as the sandbox `crypto` global, which ADK reads first, and as the
 * `node:crypto` module its fallback and `uuid`'s node builds import — so ids
 * are well-formed and regenerate identically on replay.
 */

import test from 'ava';
import { Worker } from '@temporalio/worker';

import { GoogleAdkPlugin } from '../index';
import { REUSE_V8_CONTEXT, setupTestEnv, uid, withWorker, workflowsPath } from './helpers';
import * as activities from './test-activities';
import { cryptoShimProbe } from './workflows';

const getEnv = setupTestEnv(test);

const UUID_V4_SOURCE = '[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}';
const UUID_V4 = new RegExp(`^${UUID_V4_SOURCE}$`);
/** ADK prefixes client-generated function-call ids with `adk-`. */
const ADK_CALL_ID = new RegExp(`^adk-${UUID_V4_SOURCE}$`);

test.serial('ADK ids are v4 UUIDs that survive a full replay', async (t) => {
  const env = getEnv();
  const taskQueue = uid('adk-crypto');
  const workflowId = uid('wf-crypto');
  // The worker caches no workflows, so every task after the first replays the
  // whole history. Each value is sent through an Activity on the first (live)
  // task, and the values the Workflow finally returns are regenerated by the
  // last (replayed) task: comparing the two below proves the regeneration is
  // identical. Replay does not compare Activity inputs by itself.
  const ids = await withWorker(env, { taskQueue, plugins: [new GoogleAdkPlugin()], activities }, () =>
    env.client.workflow.execute(cryptoShimProbe, { taskQueue, workflowId })
  );
  t.regex(ids.before, UUID_V4);
  t.regex(ids.after, UUID_V4);
  t.not(ids.before, ids.after);
  t.regex(ids.callId, ADK_CALL_ID);
  // The sandbox `crypto` global is the same shim: a v4 UUID and 8 bytes of hex,
  // distinct from the ids ADK drew before it; `randomFillSync(buf, 2, 3)` fills
  // exactly the three middle bytes.
  t.regex(ids.direct, UUID_V4);
  t.regex(ids.bytes, /^[0-9a-f]{16}$/);
  t.regex(ids.filled, /^0000[0-9a-f]{6}00$/);
  t.false([ids.before, ids.after].includes(ids.direct));
  // The values the Worker really saw, once each: every task after the first is
  // a replay, and a replayed Activity resolves from history instead of running,
  // so the values returned by the final (replayed) task must equal the ones the
  // first execution recorded.
  t.deepEqual(activities.executionsFor(workflowId), [
    `echoId:${ids.before}`,
    `echoId:${ids.after}`,
    `echoId:${ids.direct}`,
    `echoId:${ids.bytes}:${ids.filled}`,
  ]);
  await Worker.runReplayHistory(
    { workflowsPath, reuseV8Context: REUSE_V8_CONTEXT, plugins: [new GoogleAdkPlugin()] },
    await env.client.workflow.getHandle(workflowId).fetchHistory()
  );
});
